"""Audit original learned policy saturation and terminal cost geometry."""
import copy
import json
import numpy as np
from runtime import ART,imports,make_env
from run import write

_,SAC,_=imports()
out=ART/'results/diagnosis'
cases=json.loads((ART/'configs/vehicle_test_bank.json').read_text())['cases']
env=make_env('vehicle',211)
labels=env.control_system.controller.mpc.model._x.labels()+[p for p in env.control_system.controller.mpc.model._p.labels() if 'n_horizon' not in p]
observations=[]
for case in cases:
    ob=env.reset(**copy.deepcopy(case));done=False
    while not done:
        observations.append(ob.copy())
        ob,_,done,_=env.step(np.array([10.]))
obs=np.array(observations,dtype=np.float32)
rows=[]
for name in ['vehicle_rl_s1','vehicle_rl_s2','vehicle_fixed_h5']:
    src=ART/'results/full'/name
    files=['checkpoint_05000.zip','model.zip'] if '_rl_' in name else ['model.zip']
    for filename in files:
        m=SAC.load(str(src/filename))
        w,b=m.policy_tf.get_mpc_vfn_weights_and_biases()
        coef=w[0].ravel();n=len(coef)//2
        action=m.predict(obs,deterministic=True)[0].ravel()
        rounded=np.clip(np.rint(action),1,50)
        alpha=float(m.sess.run(m.ent_coef))
        rows.append({'model':name,'checkpoint':filename,'state_and_parameter_labels':labels,
            'linear':coef[:n].tolist(),'quadratic':coef[n:].tolist(),
            'state_hessian_eigenvalues':(2*coef[n:n+3]).tolist(),
            'state_convex':bool(np.all(coef[n:n+3]>=0)),
            'x_stationary_point':float(-coef[1]/(2*coef[n+1])),
            'x_stationary_type':'minimum' if coef[n+1]>0 else 'maximum',
            'entropy_coefficient':alpha,'common_observations':len(obs),
            'mean_horizon':float(np.mean(rounded)),'fraction_h1':float(np.mean(rounded==1)),
            'fraction_h50':float(np.mean(rounded==50)),
            'horizon_percentiles':np.percentile(rounded,[0,10,50,90,100]).tolist()})
        m.sess.close()
write(out/'regression_audit.json',{'rows':rows,'note':'Common observations generated by H10; coefficients use the original diagonal quadratic model.'})
print(json.dumps(rows,indent=2))
